import '@testing-library/jest-dom/vitest'

// jsdom doesn't implement matchMedia; the store and several components read
// prefers-reduced-motion and pointer type at start-up.
if (typeof window !== 'undefined' && !window.matchMedia) {
  window.matchMedia = (query: string) =>
    ({
      matches: false,
      media: query,
      onchange: null,
      addEventListener: () => {},
      removeEventListener: () => {},
      addListener: () => {},
      removeListener: () => {},
      dispatchEvent: () => false,
    }) as MediaQueryList
}
